-- 이미 저장된 주보는 관리자만 지울 수 있다.
--
-- 001~007 을 실행한 뒤에 이어서 실행한다.
--
-- 주보는 여럿이 함께 쓰는 기록이라, 실수로 지우면 되살릴 방법이 없다.
-- 작성·수정은 승인된 사람 누구나 그대로 할 수 있고, 삭제만 관리자에게 남긴다.
-- 화면에서도 버튼을 숨기지만, 그것만으로는 주소창이나 API로 우회할 수 있어
-- 여기 DB 정책이 실제 잠금 장치다.

-- 두 번 실행해도 탈이 없게 새 정책도 먼저 지우고 만든다.
-- 손으로 붙여넣어 돌리는 파일이라, 다시 돌렸을 때 '이미 있다'며 멈추면 안 된다.
drop policy if exists "승인자는 주보 삭제" on public.bulletins;
drop policy if exists "관리자만 주보 삭제" on public.bulletins;

create policy "관리자만 주보 삭제" on public.bulletins
  for delete using (public.is_admin());

-- 이미지 삭제는 잠그지 않는다.
-- 주보를 다시 내보내면 새 이미지 한 벌이 올라가고 지난 벌은 그 자리에서 지워야 하는데,
-- 내보내기는 승인된 사람 누구나 하는 일이기 때문이다.
-- 잠근다고 지켜지는 것도 없다 — 편집자는 어차피 주보 내용을 고칠 수 있다.
-- 여기서 막는 것은 '주보가 목록에서 통째로 사라지는 일'이고, 그건 위 정책이 맡는다.
